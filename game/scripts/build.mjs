import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const gameRoot = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: gameRoot,
  entryPoints: ['career-drive/boot.js'],
  outfile: 'career-drive/app.bundle.js',
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  // The entry HTML and bundled portrait module share the same directory.
  define: { 'import.meta.url': 'document.baseURI' },
  banner: { js: '// Generated by npm run build. Edit the source modules instead.' },
  write: false,
});

const [output] = result.outputFiles;
if (!output) throw new Error('The game build did not produce a script.');

if (process.argv.includes('--check')) {
  const current = await readFile(output.path, 'utf8');
  if (current !== output.text) {
    process.stderr.write('The game bundle is outdated. Run npm --prefix game run build.\n');
    process.exitCode = 1;
  }
} else {
  await writeFile(output.path, output.contents);
}
